-- Create an order: validates stock, decrements it, writes order + items.
-- Mirrors POST /api/orders, including the `skipped_items` response.
create or replace function public.create_order(
  p_items jsonb,
  p_customer_name text default null,
  p_customer_phone text default null,
  p_shipping_address text default null,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_skipped jsonb := '[]'::jsonb;
  v_lines jsonb := '[]'::jsonb;
  v_total numeric(12, 2) := 0;
  v_order public.orders%rowtype;
  v_items jsonb;
  v_number text;
begin
  if v_uid is null then
    raise exception 'Unauthorized';
  end if;

  select * into v_profile from public.profiles where id = v_uid;
  if not found then
    raise exception 'User not found';
  end if;

  for v_item in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb))
  loop
    v_product := null;
    select * into v_product
    from public.products
    where id = nullif(v_item ->> 'product_id', '')::bigint;

    if not found then
      v_skipped := v_skipped || jsonb_build_array(jsonb_build_object(
        'name', coalesce(v_item ->> 'name', 'Unknown'),
        'reason', 'Product not found'
      ));
      continue;
    end if;

    v_qty := greatest(coalesce((v_item ->> 'quantity')::integer, 1), 1);

    if v_product.stock < v_qty then
      v_skipped := v_skipped || jsonb_build_array(jsonb_build_object(
        'name', v_product.name,
        'reason', format('Only %s available', v_product.stock)
      ));
      continue;
    end if;

    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'product_id', v_product.id,
      'product_name', v_product.name,
      'product_price', v_product.price,
      'quantity', v_qty,
      'size', coalesce(v_item ->> 'size', ''),
      'image', coalesce(v_product.image, '')
    ));

    v_total := v_total + (v_product.price * v_qty);
  end loop;

  if jsonb_array_length(v_lines) = 0 then
    return jsonb_build_object(
      'success', false,
      'error', 'All items are out of stock',
      'skipped_items', v_skipped
    );
  end if;

  v_number := 'ORD-'
    || to_char(clock_timestamp(), 'YYMMDDHH24MISS')
    || '-'
    || upper(substr(md5(random()::text), 1, 6));

  insert into public.orders (
    order_number, user_id, customer_name, customer_email, customer_phone,
    shipping_address, status, total, notes
  ) values (
    v_number, v_uid,
    coalesce(nullif(p_customer_name, ''), v_profile.name),
    v_profile.email,
    coalesce(p_customer_phone, ''),
    coalesce(p_shipping_address, ''),
    'pending', v_total, coalesce(p_notes, '')
  )
  returning * into v_order;

  insert into public.order_items (
    order_id, product_id, product_name, product_price, quantity, size, image
  )
  select
    v_order.id,
    (l ->> 'product_id')::bigint,
    l ->> 'product_name',
    (l ->> 'product_price')::numeric,
    (l ->> 'quantity')::integer,
    l ->> 'size',
    l ->> 'image'
  from jsonb_array_elements(v_lines) as l;

  update public.products p
  set stock = p.stock - (l ->> 'quantity')::integer,
      updated_at = now()
  from jsonb_array_elements(v_lines) as l
  where p.id = (l ->> 'product_id')::bigint;

  select coalesce(jsonb_agg(to_jsonb(oi) order by oi.id), '[]'::jsonb)
  into v_items
  from public.order_items oi
  where oi.order_id = v_order.id;

  return jsonb_build_object(
    'success', true,
    'order', to_jsonb(v_order),
    'items', v_items,
    'skipped_items', case when jsonb_array_length(v_skipped) > 0 then v_skipped else null end
  );
end;
$$;

-- Replace the whole cart for the signed-in user (mirrors PUT /api/cart).
create or replace function public.replace_user_cart(p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_saved jsonb;
begin
  if v_uid is null then
    raise exception 'Unauthorized';
  end if;

  delete from public.cart_items where user_id = v_uid;

  for v_item in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb))
  loop
    v_product := null;
    select * into v_product
    from public.products
    where id = nullif(v_item ->> 'product_id', '')::bigint
      and visible = true;

    if found and v_product.stock > 0 then
      v_qty := least(
        greatest(coalesce((v_item ->> 'quantity')::integer, 1), 1),
        v_product.stock
      );

      insert into public.cart_items (user_id, product_id, product_data, quantity, size)
      values (
        v_uid,
        v_product.id::text,
        to_jsonb(v_product),
        v_qty,
        coalesce(v_item ->> 'size', '')
      )
      on conflict (user_id, product_id, size)
      do update set quantity = excluded.quantity, product_data = excluded.product_data;
    end if;
  end loop;

  select coalesce(jsonb_agg(to_jsonb(c) order by c.created_at), '[]'::jsonb)
  into v_saved
  from public.cart_items c
  where c.user_id = v_uid;

  return v_saved;
end;
$$;

-- Replace the whole wishlist for the signed-in user (mirrors PUT /api/wishlist).
create or replace function public.replace_user_wishlist(p_product_ids bigint[])
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_saved jsonb;
begin
  if v_uid is null then
    raise exception 'Unauthorized';
  end if;

  delete from public.wishlist_items where user_id = v_uid;

  insert into public.wishlist_items (user_id, product_id, product_data)
  select v_uid, p.id::text, to_jsonb(p)
  from public.products p
  where p.id = any (coalesce(p_product_ids, '{}'::bigint[]))
    and p.visible = true
  on conflict (user_id, product_id) do nothing;

  select coalesce(jsonb_agg(to_jsonb(w) order by w.created_at), '[]'::jsonb)
  into v_saved
  from public.wishlist_items w
  where w.user_id = v_uid;

  return v_saved;
end;
$$;

-- Admin order status changes, with restock-on-cancel (mirrors PATCH /orders/:id/status).
create or replace function public.admin_update_order_status(
  p_order_id bigint,
  p_status text,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  if p_status not in ('pending', 'processing', 'shipped', 'delivered', 'cancelled') then
    raise exception 'Invalid status';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order not found';
  end if;

  if p_status = 'cancelled' and v_order.status <> 'cancelled' then
    update public.products p
    set stock = p.stock + oi.quantity,
        updated_at = now()
    from public.order_items oi
    where oi.order_id = v_order.id
      and oi.product_id = p.id;
  end if;

  update public.orders
  set status = p_status,
      notes = coalesce(p_notes, notes)
  where id = v_order.id
  returning * into v_order;

  return to_jsonb(v_order);
end;
$$;

-- Storefront review list + stats (needs profile names, which are otherwise private).
create or replace function public.get_product_reviews(p_slug text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_product_id bigint;
  v_reviews jsonb;
  v_count integer;
  v_average numeric;
begin
  select id into v_product_id from public.products where slug = p_slug;
  if v_product_id is null then
    raise exception 'Product not found';
  end if;

  select coalesce(jsonb_agg(row_json order by created_at desc), '[]'::jsonb)
  into v_reviews
  from (
    select
      jsonb_build_object(
        'id', r.id,
        'rating', r.rating,
        'body', r.body,
        'created_at', r.created_at,
        'user_name', p.name
      ) as row_json,
      r.created_at
    from public.reviews r
    join public.profiles p on p.id = r.user_id
    where r.product_id = v_product_id
  ) rows;

  select count(*), coalesce(round(avg(rating)::numeric, 1), 0)
  into v_count, v_average
  from public.reviews
  where product_id = v_product_id;

  return jsonb_build_object(
    'reviews', v_reviews,
    'stats', jsonb_build_object('count', v_count, 'average', v_average)
  );
end;
$$;

-- Admin dashboard aggregates.
create or replace function public.admin_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  return jsonb_build_object(
    'stats', jsonb_build_object(
      'totalProducts', (select count(*) from public.products),
      'totalOrders', (select count(*) from public.orders),
      'totalRevenue', (
        select coalesce(sum(total), 0) from public.orders where status <> 'cancelled'
      ),
      'totalCustomers', (select count(*) from public.profiles where role = 'customer'),
      'ordersByStatus', (
        select coalesce(jsonb_agg(jsonb_build_object('status', s.status, 'count', s.cnt)), '[]'::jsonb)
        from (
          select status, count(*) as cnt from public.orders group by status
        ) s
      )
    ),
    'recentOrders', (
      select coalesce(jsonb_agg(to_jsonb(o) order by o.created_at desc), '[]'::jsonb)
      from (
        select * from public.orders order by created_at desc limit 5
      ) o
    )
  );
end;
$$;

-- One-time helper: realign identity sequences after importing legacy rows
-- with explicit ids. Service-role only.
create or replace function public.migrate_reset_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform setval(
    pg_get_serial_sequence('public.products', 'id'),
    coalesce((select max(id) from public.products), 0) + 1,
    false
  );
  perform setval(
    pg_get_serial_sequence('public.orders', 'id'),
    coalesce((select max(id) from public.orders), 0) + 1,
    false
  );
  perform setval(
    pg_get_serial_sequence('public.order_items', 'id'),
    coalesce((select max(id) from public.order_items), 0) + 1,
    false
  );
  perform setval(
    pg_get_serial_sequence('public.testimonials', 'id'),
    coalesce((select max(id) from public.testimonials), 0) + 1,
    false
  );
  perform setval(
    pg_get_serial_sequence('public.reviews', 'id'),
    coalesce((select max(id) from public.reviews), 0) + 1,
    false
  );
  perform setval(
    pg_get_serial_sequence('public.cart_items', 'id'),
    coalesce((select max(id) from public.cart_items), 0) + 1,
    false
  );
  perform setval(
    pg_get_serial_sequence('public.wishlist_items', 'id'),
    coalesce((select max(id) from public.wishlist_items), 0) + 1,
    false
  );
end;
$$;

